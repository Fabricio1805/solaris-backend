create table employee (
                          active boolean,
                          address_id bigint,
                          company_id bigint,
                          created_at timestamp(6),
                          created_id bigint,
                          id bigint generated by default as identity,
                          specialty_id bigint,
                          updated_at timestamp(6),
                          updated_id bigint,
                          color_calendar varchar(255),
                          primary key (id)
)