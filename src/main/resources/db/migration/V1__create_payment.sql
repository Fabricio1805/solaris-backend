create table payment (
                         amount numeric(38,2),
                         appointment_id bigint,
                         created_at timestamp(6),
                         created_id bigint,
                         id bigint generated by default as identity,
                         paid_at timestamp(6),
                         updated_at timestamp(6),
                         updated_id bigint,
                         payment_method enum ('BANK_TRANSFER','CASH','CREDIT_CARD','DEBIT_CARD','PIX'),
                         status enum ('CANCELLED','PAID','PENDING','REFUNDED'),
                         primary key (id)
)