create table address (
                         id bigint generated by default as identity,
                         created_at timestamp(6),
                         created_id bigint,
                         updated_at timestamp(6),
                         updated_id bigint,

                         city varchar(255),
                         complement varchar(255),
                         country varchar(255),
                         neighborhood varchar(255),
                         number varchar(255),
                         state varchar(255),
                         street varchar(255),
                         zip_code varchar(255),

                         primary key (id)
);
