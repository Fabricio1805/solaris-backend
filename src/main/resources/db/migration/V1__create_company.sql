create table company (
                         address_id bigint,
                         created_at timestamp(6),
                         created_id bigint,
                         id bigint generated by default as identity,
                         updated_at timestamp(6),
                         updated_id bigint,
                         corporate_name varchar(255),
                         document varchar(255),
                         email varchar(255),
                         name varchar(255),
                         phone varchar(255),
                         document_type enum ('CNPJ','CPF','PASSPORT'),
                         primary key (id)
)