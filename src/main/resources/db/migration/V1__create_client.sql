create table client (
                        birthday date,
                        address_id bigint,
                        company_id bigint,
                        created_at timestamp(6),
                        created_id bigint,
                        id bigint generated by default as identity,
                        updated_at timestamp(6),
                        updated_id bigint,
                        email varchar(255),
                        name varchar(255),
                        phone varchar(255),
                        primary key (id)
)