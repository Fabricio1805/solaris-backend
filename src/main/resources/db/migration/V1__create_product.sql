create table product (
                         active boolean,
                         price numeric(38,2),
                         created_at timestamp(6),
                         created_id bigint,
                         id bigint generated by default as identity,
                         updated_at timestamp(6),
                         updated_id bigint,
                         description varchar(255),
                         name varchar(255),
                         photo varchar(255),
                         primary key (id)
)