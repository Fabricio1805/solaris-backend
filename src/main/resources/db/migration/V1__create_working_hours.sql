create table working_hours (
                               end_time time(0),
                               start_time time(0),
                               company_id bigint,
                               created_at timestamp(6),
                               created_id bigint,
                               id bigint generated by default as identity,
                               updated_at timestamp(6),
                               updated_id bigint,
                               day_of_week enum ('FRIDAY','MONDAY','SATURDAY','SUNDAY','THURSDAY','TUESDAY','WEDNESDAY'),
                               primary key (id)
)