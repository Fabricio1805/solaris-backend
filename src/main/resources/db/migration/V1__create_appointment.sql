create table appointment (
                             id bigint generated by default as identity,
                             created_at timestamp(6),
                             created_id bigint,
                             updated_at timestamp(6),
                             updated_id bigint,

                             commission numeric(38,2),
                             price numeric(38,2),
                             client_id bigint,
                             company_id bigint,
                             employee_id bigint,
                             end_time timestamp(6),
                             service_id bigint,
                             start_time timestamp(6),
                             notes varchar(255),
                             status enum ('CANCELLED','CHECKED_IN','COMPLETED','CONFIRMED','IN_PROGRESS','NO_SHOW','RESCHEDULED','SCHEDULED'),

                             primary key (id)
);